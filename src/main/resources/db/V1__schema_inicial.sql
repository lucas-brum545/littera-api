-- 1. Tabela de Usuários
CREATE TABLE public.usuario (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                nome VARCHAR(255) NOT NULL,
                                email VARCHAR(255) NOT NULL,
                                senha_hash VARCHAR(72),
                                telefone VARCHAR(30) NOT NULL,
                                data_nascimento DATE NOT NULL,
                                tipo_usuario VARCHAR(20) NOT NULL,
                                bloqueado BOOLEAN NOT NULL DEFAULT FALSE,
                                data_fim_bloqueio DATE,
                                quantidade_emprestada INTEGER NOT NULL DEFAULT 0,

                                CONSTRAINT pk_usuario PRIMARY KEY (id),
                                CONSTRAINT uk_usuario_email UNIQUE (email),
                                CONSTRAINT ck_tipo_usuario CHECK (tipo_usuario IN ('LEITOR', 'ADMIN'))
);

-- 2. Tabela Base do Acervo (Herança JPA: Joined Table)
CREATE TABLE public.item_acervo (
                                    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                    titulo VARCHAR(200) NOT NULL,
                                    descricao TEXT,
                                    ano INTEGER,
                                    idioma VARCHAR(20),
                                    localizacao VARCHAR(50) NOT NULL,
                                    capa TEXT,
                                    total_disponivel INTEGER,
                                    total_emprestados INTEGER,
                                    cadastrado_em DATE,
                                    link_google VARCHAR(255),
                                    link_crossref VARCHAR(255),
                                    tipo VARCHAR(255) NOT NULL,

                                    CONSTRAINT pk_item_acervo PRIMARY KEY (codigo),
                                    CONSTRAINT ck_item_tipo CHECK (tipo IN ('LIVRO', 'REVISTA'))
);

-- 3. Tabela de Livros (Herda de item_acervo)
CREATE TABLE public.livro (
                              codigo BIGINT NOT NULL,
                              autor VARCHAR(100) NOT NULL,
                              isbn VARCHAR(20) NOT NULL,
                              genero VARCHAR(50) NOT NULL,

                              CONSTRAINT pk_livro PRIMARY KEY (codigo),
                              CONSTRAINT fk_livro_item_acervo FOREIGN KEY (codigo)
                                  REFERENCES public.item_acervo (codigo)
                                  ON UPDATE CASCADE
                                  ON DELETE CASCADE
);

-- 4. Tabela de Revistas (Herda de item_acervo)
CREATE TABLE public.revista (
                                codigo BIGINT NOT NULL,
                                issn VARCHAR(20) NOT NULL,
                                edicao VARCHAR(10) NOT NULL,
                                mes_ano_publicacao VARCHAR(7) NOT NULL,

                                CONSTRAINT pk_revista PRIMARY KEY (codigo),
                                CONSTRAINT fk_revista_item_acervo FOREIGN KEY (codigo)
                                    REFERENCES public.item_acervo (codigo)
                                    ON UPDATE CASCADE
                                    ON DELETE CASCADE
);

-- 5. Tabela de Reservas
CREATE TABLE public.reserva (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                usuario_id BIGINT NOT NULL,
                                item_codigo BIGINT NOT NULL,
                                data_reserva DATE,
                                status VARCHAR(9) NOT NULL,

                                CONSTRAINT pk_reserva PRIMARY KEY (id),
                                CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_id)
                                    REFERENCES public.usuario (id)
                                    ON UPDATE CASCADE
                                    ON DELETE RESTRICT,
                                CONSTRAINT fk_reserva_item FOREIGN KEY (item_codigo)
                                    REFERENCES public.item_acervo (codigo)
                                    ON UPDATE CASCADE
                                    ON DELETE RESTRICT
);

-- 6. Tabela de Empréstimos
CREATE TABLE public.emprestimo (
                                   codigo BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                   data_emprestimo DATE NOT NULL,
                                   data_devolucao_prevista DATE NOT NULL,
                                   data_devolucao_real DATE,
                                   codigo_item_acervo BIGINT NOT NULL,
                                   codigo_usuario BIGINT NOT NULL,

                                   CONSTRAINT pk_emprestimo PRIMARY KEY (codigo),
                                   CONSTRAINT fk_emprestimo_item_acervo FOREIGN KEY (codigo_item_acervo)
                                       REFERENCES public.item_acervo (codigo)
                                           MATCH SIMPLE
                                       ON UPDATE CASCADE
                                       ON DELETE RESTRICT,
                                   CONSTRAINT fk_emprestimo_usuario FOREIGN KEY (codigo_usuario)
                                       REFERENCES public.usuario (id)
                                           MATCH SIMPLE
                                       ON UPDATE CASCADE
                                       ON DELETE RESTRICT,
                                   CONSTRAINT ck_datas CHECK (data_devolucao_prevista IS NULL OR data_devolucao_prevista >= data_emprestimo)
);